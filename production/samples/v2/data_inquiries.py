def generate() -> list[dict]:
    rng = random.Random(SEED)
    assert len(ENTRIES) == 60
    names: set[str] = set()
    rows = []
    for cat, prod, text, has_order in ENTRIES:
        lo_day, hi_day = TS_WINDOW.get(next((k for k in TS_WINDOW if k in text), ""), (1, 25))
        day = rng.randint(lo_day, hi_day)
        ts = dt.datetime(2026, 10, day, rng.randint(8, 21), rng.randint(0, 59))
        while True:
            nm = rng.choice(SURNAMES) + rng.choice(GIVEN)
            if nm not in names:
                names.add(nm)
                break
        rows.append({"_cat": cat, "접수일시": ts, "채널": rng.choice(CHANNELS), "고객명(가상)": nm, "제품": prod,
                     "_has_order": has_order, "문의내용": text})
    rows.sort(key=lambda r: r["접수일시"])
    for i, r in enumerate(rows, start=1):
        r["문의번호"] = f"CS-2610-{i:03d}"
        rule = next((v for k, v in ORDER_DATE.items() if k in r["문의내용"]), None)
        if isinstance(rule, dt.date):
            d = rule
        else:
            d = (r["접수일시"] - dt.timedelta(days=rule if rule is not None else rng.randint(2, 8))).date()
        assert d < r["접수일시"].date(), (r["문의내용"], d)
        r["주문번호"] = f"CY{d:%y%m%d}-{rng.randint(1000, 9999)}" if r["_has_order"] else ""
    return rows


